// ==============================|| CHANNEL BRAND ICONS ||============================== //
// Official brand marks set on an app-icon tile in each brand's colour.
// Website / Email have no single brand, so they use neutral chat + envelope glyphs; Lazada is
// not in Simple Icons and uses its gradient heart.
// API mirrors @tabler/icons-react: `{ size }`. Passing `color` renders the bare glyph in that colour
// (for monochrome contexts) instead of the coloured tile.

const GLYPH = 'translate(4.4 4.4) scale(0.633)'

const Tile = ({ size, color, bg, glyph, extra }) => {
    const gid = `ch-${useId().replace(/:/g, '')}`
    if (color) {
        return (
            <svg width={size} height={size} viewBox='0 0 24 24' aria-hidden>
                <path d={glyph} fill={color} />
            </svg>
        )
    }
    const fill = bg.solid || `url(#${gid})`
    return (
        <svg width={size} height={size} viewBox='0 0 24 24' aria-hidden style={{ display: 'block', flexShrink: 0 }}>
            {bg.grad && (
                <defs>
                    {bg.grad[0] === 'radial' ? (
                        <radialGradient id={gid} cx='0.2' cy='1.05' r='1.3'>
                            {bg.grad[1].map(([o, c]) => (
                                <stop key={o} offset={o} stopColor={c} />
                            ))}
                        </radialGradient>
                    ) : (
                        <linearGradient id={gid} x1='0' y1='1' x2='1' y2='0'>
                            {bg.grad[1].map(([o, c]) => (
                                <stop key={o} offset={o} stopColor={c} />
                            ))}
                        </linearGradient>
                    )}
                </defs>
            )}
            <rect width='24' height='24' rx='6' fill={fill} />
            {/* soft top sheen, like a real app icon */}
            <rect width='24' height='12' rx='6' fill='#fff' opacity='0.08' />
            {extra === 'tiktok' ? (
                <g transform={GLYPH}>
                    <path d={glyph} fill='#25F4EE' transform='translate(-0.9 -0.7)' />
                    <path d={glyph} fill='#FE2C55' transform='translate(0.9 0.7)' />
                    <path d={glyph} fill='#fff' />
                </g>
            ) : (
                <g transform={GLYPH}>
                    <path d={glyph} fill='#fff' />
                </g>
            )}
            {extra === 'badge' && (
                // personal account: small person badge
                <g>
                    <circle cx='18.6' cy='18.6' r='4.2' fill='#fff' />
                    <circle cx='18.6' cy='17.4' r='1.3' fill='#00A8FF' />
                    <path d='M16.3 20.9c.4-1.1 1.3-1.7 2.3-1.7s1.9.6 2.3 1.7' fill='#00A8FF' />
                </g>
            )}
        </svg>
    )
}

Tile.propTypes = {
    size: PropTypes.number,
    color: PropTypes.string,
    bg: PropTypes.object.isRequired,
    glyph: PropTypes.string.isRequired,
    extra: PropTypes.string
}

const brand = (bg, glyph, extra) => {
    const Icon = ({ size = 24, color }) => <Tile size={size} color={color} bg={bg} glyph={glyph} extra={extra} />
    Icon.propTypes = { size: PropTypes.number, color: PropTypes.string }
    return Icon
}

